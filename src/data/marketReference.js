/** Квантил с линейна интерполация (q от 0 до 1). */
export function quantile(values, q) {
  const s = [...values].sort((a, b) => a - b);
  if (!s.length) return NaN;
  const pos = (s.length - 1) * q;
  const lo = Math.floor(pos);
  const hi = Math.ceil(pos);
  return s[lo] + (s[hi] - s[lo]) * (pos - lo);
}

export const median = (values) => quantile(values, 0.5);

const roundHalf = (x) => Math.round(x * 2) / 2;

/** Референтна цена (медиана на точките, закръглена до 0,50 €) или наша оценка. */
export function referencePrice(sid) {
  const pts = REFERENCE_POINTS[sid] || [];
  if (pts.length) {
    const national = pts.every((x) => SOURCES[x.src]?.national);
    return { price: roundHalf(median(pts.map((x) => x.value))), estimated: false, national, points: pts.length };
  }
  return { price: ESTIMATES[sid] ?? 0, estimated: true, national: false, points: 0 };
}
