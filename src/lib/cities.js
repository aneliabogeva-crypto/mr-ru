// Градове за избор от падащо меню. Майсторите и клиентите избират от същия
// списък, за да съвпада градът точно (София → София).

export const CITIES = [
  "София", "Пловдив", "Варна", "Бургас", "Русе", "Стара Загора", "Плевен", "Сливен", "Добрич", "Шумен",
  "Перник", "Хасково", "Ямбол", "Пазарджик", "Благоевград", "Велико Търново", "Враца", "Габрово",
  "Асеновград", "Видин", "Казанлък", "Кюстендил", "Кърджали", "Монтана", "Димитровград", "Ловеч",
  "Силистра", "Търговище", "Разград", "Дупница", "Горна Оряховица", "Смолян", "Петрич", "Сандански",
  "Самоков", "Банско", "Несебър", "Поморие", "Свищов", "Карлово",
];

/** „гр. София, кв. Младост“ → „софия“. */
export function normalizeCity(s) {
  return String(s || "")
    .split(",")[0]
    .replace(/^\s*(гр\.|град)\s*/i, "")
    .trim()
    .toLowerCase();
}

export const sameCity = (a, b) => !!normalizeCity(a) && normalizeCity(a) === normalizeCity(b);

/** Името на града от списъка за даден текст, или самият текст. */
export function canonicalCity(s) {
  const n = normalizeCity(s);
  return CITIES.find((c) => c.toLowerCase() === n) || String(s || "").split(",")[0].trim();
}
